    <h1>Data Retention Policy</h1>
    <p class="last-updated">Last updated: June 19, 2026</p>

    <p>This Data Retention Policy explains how Ledge Top Technologies LLC ("we," "us," or "Ledge Top Technologies") retains, archives, and deletes data associated with Project Alpha ("the Service").</p>

    <h2>1. Active Accounts</h2>
    <p>While your account remains active, we retain your data so that you can access and manage your quotes, contracts, invoices, clients, organizations, and other business records through the Service.</p>

    <h2>2. Account Closure Grace Period</h2>
    <p>When an account is closed, either by you or by us, the account enters a 30-day grace period. During this period, the data remains stored but access to the Service may be suspended or restricted. You may request export of your data during this period.</p>

    <h2>3. Permanent Deletion</h2>
    <p>After the 30-day grace period expires, we begin permanent deletion of account data. This process generally completes within 30 additional days, unless technical or legal circumstances require a longer period.</p>

    <h2>4. Exceptions</h2>
    <p>Even after account closure, we may retain certain data as required by law, regulation, or legitimate business needs, including:</p>
    <ul>
      <li>Payment and billing records for tax, accounting, and fraud-prevention purposes.</li>
      <li>Audit logs and security records to protect the Service and comply with legal obligations.</li>
      <li>Data necessary to resolve disputes, enforce agreements, or defend legal claims.</li>
    </ul>

    <h2>5. Backups</h2>
    <p>Backups of Service data are retained for a limited period for disaster-recovery purposes. Deleted data may persist in encrypted backups until those backups are rotated out according to our backup retention schedule.</p>

    <h2>6. Data Export</h2>
    <p>During the account closure grace period, you may request an export of your data. We will make reasonable efforts to provide the export in a commonly used electronic format.</p>

    <h2>7. Changes to This Policy</h2>
    <p>We may update this Data Retention Policy from time to time. Material changes will be communicated with at least 30 days' notice. Continued use of the Service after the effective date constitutes acceptance of the revised policy.</p>

    <h2>8. Contact Us</h2>
    <p>For questions about this Data Retention Policy or to request data export or deletion, please contact us at <a href="mailto:privacy@ledgetoptechnologies.com">privacy@ledgetoptechnologies.com</a>.</p>

